import {createHash} from 'node:crypto';
import {readFile,writeFile} from 'node:fs/promises';

const root=new URL('../',import.meta.url);
async function receipt(file) {
  const bytes=await readFile(new URL('release/review-web/'+file,root));
  return {data:JSON.parse(bytes.toString('utf8').replace(/^\uFEFF/u,'')),source:{file,sha256:createHash('sha256').update(bytes).digest('hex')}};
}
const blueprint=await receipt('guided-team-blueprint.json');
const studio=await receipt('meeting-studio-qa.json');
const fund=await receipt('forward-hosted.json');
const {decision,order,cashCents,unitsMicros}=fund.data;
if(decision.record.proposal.action!=='REBALANCE'||order.status!=='authorized'||order.decisionId!==decision.id||order.seal!==decision.seal||order.fills.length||Object.keys(unitsMicros).length) throw new Error('Review the storyline against this changed allocation receipt.');
if(studio.data.studio.execution!=='held'||studio.data.studio.cashBefore!==studio.data.studio.cashAfter||!blueprint.data.confirmWasShown) throw new Error('Review the Studio storyline against the changed receipts.');
const view={
  blueprint:{source:blueprint.source,at:blueprint.data.checkedAt,seats:blueprint.data.proposedSeatCount,
    model:blueprint.data.receipts.at(-1).model,actions:blueprint.data.actionsAtBlueprint,confirmation:blueprint.data.confirmWasShown},
  studio:{source:studio.source,receipt:studio.data.studio.requestId,decision:studio.data.studio.execution,
    events:studio.data.studio.eventCount,replies:studio.data.studio.realReceipts.length,before:studio.data.studio.cashBefore,after:studio.data.studio.cashAfter},
  allocation:{source:fund.source,cutoff:decision.record.cutoff,sealedAt:decision.sealedAt,seal:decision.seal,
    ticker:decision.record.ticker, action:decision.record.proposal.action,targets:decision.record.proposal.targets,seats:decision.record.seats.map(seat=>seat.role),
    authorizedAt:order.approvedAt,pricingDate:order.pricingDate,cash:cashCents/100,positions:Object.keys(unitsMicros).length,fills:order.fills.length}
};
await writeFile(new URL('web/judge-records.js',root),'/* Local excerpts generated by scripts/build-judge-replay.mjs. */\nwindow.judgeRecords = '+JSON.stringify(view,null,2)+';\n');

